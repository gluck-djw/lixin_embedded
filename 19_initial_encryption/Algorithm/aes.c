#define BPOLY 0x1B // irreducible polynomial m(x) = x^8 + x^4 + x^3 + x + 1

/* 比函数形式节省4字节的data数据 */
#define AddRoundKey(state, pround_key) \
    xor_bytes(state, pround_key, 4 * Nb)

/*  将一个字中的4个字节循环左移一个字节 */
void rotation_word(unsigned char *word)
{
    unsigned char temp = word[0];
    word[0] = word[1];
    word[1] = word[2];
    word[2] = word[3];
    word[3] = temp;
}

void xor_bytes(unsigned char *word1, unsigned char *word2, unsigned char nCount)
{
    unsigned char i;
    for (i = 0; i < nCount; i++)
    {
        word1[i] ^= word2[i];
    }
}

/* 用s盒子置换状态数据 */
static void sub_bytes(unsigned char *word, unsigned char nCount, bool bInvert)
{
    unsigned char i;
    const unsigned char *pSBox = bInvert ? sbox_inv : sbox; // 根据是否需要解密选择s盒
    for (i = 0; i < nCount; i++)
    {
        word[i] = pSBox[word[i]];
    }
}

// /* GF（2^8）有限域乘法 */
uint8_t gmult(uint8_t a, uint8_t b)
{
    uint8_t i, p = 0, hbs = 0;
    for (i = 0; i < 8; i++)
    {
        if (b & 1)
        {
            p ^= a;
        }
        hbs = a & 0x80;
        a <<= 1; // 左移是因为我们从 b 的最低位开始往上处理，位权是 2⁰→2¹→2²→…，每往高走一位

        if (hbs)
        {
            a = a ^ BPOLY; // 溢出 → 模 m(x) 约减，异或 0x1B
        }
        b >>= 1; // 右移是保证最低位是当前计算位
    }
    return p;
}

