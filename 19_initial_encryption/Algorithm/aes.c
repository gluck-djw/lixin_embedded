unsigned char gf_mult(unsigned char num)
{
    if ((num & 0x80) == 0)
    {
        num = num << 1;
    }
    else
    {
        num = (num << 1) ^ 0x1b;
    }
    return num;
}

/* 第一行不变， 第二行左移1字节， 第三行左移2字节， 第四行左移3字节
shift(1,4)=1; shift(2,4)=2; shift(3,4)=3 */

void shift_rows(unsigned char *word, bool bInvert)
{
    unsigned char temp;
    unsigned char rowdata[Nb];
    unsigned char i, j;
    for (i = 1; i < 4; i++) /* 第1~3行，第0行不动 */
    {
        for (j = 0; j < Nb; j++) // 先把第 i 行原始数据存好
        {
            rowdata[j] = word[i + j * Nb];
        }

        temp = bInvert ? (Nb - i) : i; // 逆序时，左移变成右移
        for (j = 0; j < Nb; j++)
        {
            word[i + j * Nb] = rowdata[(temp + j) % Nb];
        }
    }
}

void coefmul(uint8_t *a, uint8_t *b, uint8_t *res)
{
    res[0] = gmult(a[0], b[0]) ^ gmult(a[1], b[1]) ^ gmult(a[2], b[2]) ^ gmult(a[3], b[3]);
    res[1] = gmult(a[3], b[0]) ^ gmult(a[0], b[1]) ^ gmult(a[1], b[2]) ^ gmult(a[2], b[3]);
    res[2] = gmult(a[2], b[0]) ^ gmult(a[3], b[1]) ^ gmult(a[0], b[2]) ^ gmult(a[1], b[3]);
    res[3] = gmult(a[1], b[0]) ^ gmult(a[2], b[1]) ^ gmult(a[3], b[2]) ^ gmult(a[0], b[3]);
}

void mix_columns(uint8_t *word, bool inv)
{
    uint8_t a[] = {0x02, 0x03, 0x01, 0x01};
    uint8_t b[] = {0x0e, 0x0b, 0x0d, 0x09};
    uint8_t i, j, *tmp, col[4], res[4];

    for (j = 0; j < Nb; j++)
    {
        for (i = 0; i < 4; i++)
        {
            col[i] = word[i  + j* Nb];
        }
        tmp = inv ? b : a;
        coefmul(tmp, col, res);

        for (i = 0; i < 4; i++)
        {
            word[i  + j* Nb] = res[i];
        }
    }
}

/* 主密钥 密钥扩展 -> 一串轮密钥 */
void AES_key_expansion(const void *key)
{
    unsigned char i;
    unsigned char *pround_key;

    unsigned char Rcon[4] = {0x01, 0x00, 0x00, 0x00}; // 轮常量
    memcpy(g_roundKeyTable, key, Nk * 4);

    pround_key = &g_roundKeyTable[Nk * 4]; // 指向字节16 = w[4] 的开头

    for (i = Nk; i < Nb * (Nr + 1); pround_key += 4, i++)
    {
        memcpy(pround_key, pround_key - 4, Nk);
        if (i % Nk == 0)
        {
            // 字循环
            rotation_word(pround_key);
            // 字节代换：对字循环后的字节进行字节代换
            sub_bytes(pround_key, 4, false);
            // 轮常量异或
            xor_bytes(pround_key, Rcon, 4);
            Rcon[0] = gf_mult(Rcon[0]);
        }
        else if (Nk > 6 && i % Nk == 4) // 仅 AES-256
        {
            sub_bytes(pround_key, 4, false); // 只过 S 盒，不旋转、不加
        }
        xor_bytes(pround_key, pround_key - Nk * 4, 4);
    }
}

/* 对单块数据加密 */
static void block_encrypt(unsigned char *pState)
{
    AddRoundKey(pState, g_roundKeyTable);
    for (int i = 1; i <= Nr; i++)
    {
        // 字节代换
        sub_bytes(pState, 4 * Nb, false);
        // 行移位
        shift_rows(pState, false);
        if (i != Nr)
        {
            // 列混合
            mix_columns(pState, false);
        }

        // 轮密钥加
        AddRoundKey(pState, g_roundKeyTable + i * 4 * Nb);
    }
}

/* 对单块数据解密 */
static void block_decrypt(unsigned char *pState)
{
    AddRoundKey(pState, g_roundKeyTable + Nr * 4 * Nb);
    for (int i = Nr; i > 0; i--)
    {
        shift_rows(pState, true);
        sub_bytes(pState, 4 * Nb, true);

        AddRoundKey(pState, g_roundKeyTable + (i - 1) * 4 * Nb);
        if (i != 1)
        {
            mix_columns(pState, true);
        }
    }
}

/* 加密数据 */
void AES_encrypt(unsigned char *pPlaintext, unsigned char *pCipherText, unsigned int nDataLen, unsigned char *pIV)
{
    unsigned char i;
    if (pPlaintext != pCipherText)
    {
        memcpy(pCipherText, pPlaintext, nDataLen);
    }
    for (i = nDataLen / (4 * Nb); i > 0; i--, pCipherText += 4 * Nb)
    {
#if AES_MODE == CBC
        xor_bytes(pCipherText, pIV, 4 * Nb);
#endif
        block_encrypt(pCipherText);
        pIV = pCipherText;
    }
}

/* 解密数据 */
void AES_decrypt(unsigned char *pCipherText, unsigned char *pPlaintext, unsigned int nDataLen, unsigned char *pIV)
{
    unsigned char i;
    if (pPlaintext != pCipherText)
    {
        memcpy(pPlaintext, pCipherText, nDataLen);
    }
    // 从最后一块数据开始解密
    pPlaintext += nDataLen - 4 * Nb;
    for (i = nDataLen / (4 * Nb); i > 0; i--, pPlaintext -= 4 * Nb)
    {
        block_decrypt(pPlaintext);
#if AES_MODE == CBC
        if (i == 1) // 最后一块
        {
            xor_bytes(pPlaintext, pIV, 4 * Nb);
        }
        else
        {
            xor_bytes(pPlaintext, pPlaintext - 4 * Nb, 4 * Nb);
        }
#endif
    }
}
